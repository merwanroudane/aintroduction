# ---------------------------------------------------------------- 2. the topic bank

with tab_bank:
    st.markdown(data["intro"])

    all_topics = [(ax, t) for ax in data["axes"] for t in ax["topics"]]
    disciplines = sorted({f for _, t in all_topics for f in t["fits"] if f != "الكل"})

    f1, f2 = st.columns([2, 1])
    axis_names = {ax["id"]: ax["title"] for ax in data["axes"]}
    chosen_axes = f1.multiselect("المحور", list(axis_names), format_func=axis_names.get,
                                 default=list(axis_names), key="td_axes")
    discipline = f2.selectbox("التخصص", ["كل التخصصات", *disciplines], key="td_fits")

    g1, g2 = st.columns(2)
    levels = g1.pills("المستوى", [1, 2, 3], format_func=lambda n: data["levels"][n].split("—")[0].strip(),
                      selection_mode="multi", default=[1, 2, 3], key="td_levels")
    kinds = g2.pills("النوع", ["نظري", "مختلط", "تطبيقي"], selection_mode="multi",
                     default=["نظري", "مختلط", "تطبيقي"], key="td_kinds")

    def keep(t: dict) -> bool:
        if levels and t["level"] not in levels:
            return False
        if kinds and t["kind"] not in kinds:
            return False
        if discipline != "كل التخصصات" and discipline not in t["fits"] and "الكل" not in t["fits"]:
            return False
        return True

    shown = 0
    for ax in data["axes"]:
        if ax["id"] not in chosen_axes:
            continue
        topics = [t for t in ax["topics"] if keep(t)]
        if not topics:
            continue
        shown += len(topics)
        chips = "".join(
            f'<span class="modchip" style="--c:{MODULE_COLORS[n].accent};'
            f'--b:{MODULE_COLORS[n].tint};--d:{MODULE_COLORS[n].deep}">المحور {n}</span>'
            for n in ax["modules"]
        )
        st.markdown(f"#### {ax['title']}")
        st.html(f'<div class="modchips">{chips}</div>')
        st.caption(ax["note"])
        for t in topics:
            with st.container(border=True, key=f"td-{t['n']}"):
                badge = {"نظري": "blue", "مختلط": "violet", "تطبيقي": "green"}[t["kind"]]
                lvl = {1: "gray", 2: "orange", 3: "red"}[t["level"]]
                st.markdown(
                    f"**{t['n']}. {t['title']}**  \n"
                    f":{badge}-badge[{t['kind']}] "
                    f":{lvl}-badge[{data['levels'][t['level']].split('—')[0].strip()}]"
                )
                st.markdown(f"**الجزء التطبيقي المطلوب:** {t['applied']}")
                cols = st.columns(min(len(t["modules"]), 4))
                for col, n in zip(cols, t["modules"]):
                    with col:
                        link_to_module(n, label=f"المحور {n}")
    if not shown:
        st.info("لا يوجد موضوع يطابق هذه المرشّحات. وسّع الاختيار.")
    else:
        st.caption(f"معروض: **{shown}** موضوعًا من أصل 65.")

