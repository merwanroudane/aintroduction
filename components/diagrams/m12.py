@register("m12_identifiability")
def identifiability() -> None:
    st.caption("كيف تنمو **قابلية التعرّف** بعدد الصفات المعروفة عن الشخص — ولا اسم بينها. "
               "محاكاة على مجتمع مصطنع من 50,000 شخص.")
    attrs = [
        ("الجنس", 2), ("الفئة العمرية", 10), ("الحالة المدنية", 4), ("المستوى التعليمي", 6),
        ("القطاع المهني", 9), ("حجم الأسرة", 8), ("البلدية", 60), ("شهر الميلاد", 12),
        ("نوع السكن", 5), ("وسيلة التنقل", 6),
    ]
    n = 50_000
    rng = np.random.default_rng(12)
    cols = []
    for _, k in attrs:
        # Non-uniform (Zipf-like) category weights: more realistic than uniform, and it LOWERS
        # uniqueness relative to uniform, so the curve is not inflated by an easy assumption.
        w = 1.0 / np.arange(1, k + 1)
        w /= w.sum()
        cols.append(rng.choice(k, size=n, p=w))
    frac = []
    for i in range(1, len(attrs) + 1):
        keys = np.stack(cols[:i], axis=1)
        _, inv, counts = np.unique(keys, axis=0, return_inverse=True, return_counts=True)
        frac.append(float((counts[inv] == 1).mean()))

    labels = [a for a, _ in attrs]
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=list(range(1, len(attrs) + 1)), y=frac, mode="lines+markers",
                             line=dict(color=PALETTE[0], width=3), marker=dict(size=9),
                             hovertext=[f"بإضافة: {l}" for l in labels], hoverinfo="text+y"))
    fig.update_xaxes(title="عدد الصفات المعروفة (بلا اسم ولا معرّف)",
                     tickmode="array", tickvals=list(range(1, len(attrs) + 1)))
    fig.update_yaxes(title="نسبة من صار فريدًا في المجتمع", tickformat=".0%", range=[0, 1.05])
    fig.update_layout(showlegend=False)
    show(fig, 380, key="m12-ident")
    st.caption(
        "**المحاكاة تبسيط**: تفترض استقلال الصفات، وتستعمل عددًا مفترضًا من الفئات لكل صفة. "
        "وقد وجدت دراسة منشورة على مجتمعات حقيقية، بطريقة إحصائية أدق، أن **15 صفة ديموغرافية تكفي "
        "للتعرّف الصحيح على 99.98٪** من سكان بلد كامل. **والدرس واحد في الحالتين:** قابلية التعرّف "
        "لا تحتاج اسمًا."
    )


