@register("m06_decomposition_planner", "خطط سلسلة أوامر لمهمة مركّبة", "Task decomposition planner", module=6)
def decomposition_planner() -> None:
    st.caption("اختر مهمة مركّبة، ثم رتّب خطواتها، ثم قارن بمخطط مرجعي. الهدف إدراك أن **مخرج كل خطوة "
               "يجب أن يكون قابلًا للتحقق** قبل أن تُبنى عليه الخطوة التالية.")
    task = st.selectbox("المهمة", list(TASKS), key="m06_decomposition_planner-task")
    steps = TASKS[task]
    st.markdown("#### المخطط المرجعي")
    for i, (name, what, output) in enumerate(steps, 1):
        with st.container(border=True, key=f"m06-dec-{task}-{i}"):
            st.markdown(f"**الخطوة {i}: {name}**  \n{what}")
            st.caption(f"المخرج: {output}")
    st.markdown("#### نقاط التحقق")
    checks = st.multiselect(
        "أين تضع نقطة تحقق بشرية أو برمجية؟ (اختر ما لا يقل عن نقطتين)",
        [f"بعد الخطوة {i}: {s[0]}" for i, s in enumerate(steps, 1)],
        key="m06_decomposition_planner-checks")
    if len(checks) >= 2:
        st.success(f"اخترت {len(checks)} نقاط تحقق. **القاعدة:** ضع نقطة تحقق بعد كل خطوة "
                   "يتضخم خطؤها في الخطوات التالية، وخصوصًا بعد **الاستخراج** لأن كل ما بعده يعتمد عليه.")
    elif checks:
        st.info("أضف نقطة أخرى على الأقل: الخطوة الأولى (الاستخراج) تحتاج إلى تحقق دائمًا.")
    st.caption("**تنبيه:** التفكيك ليس دائمًا الأفضل. مهمة بسيطة مفككة إلى ست خطوات تصبح أبطأ وأغلى "
               "وأكثر عرضة لأخطاء الوصل بين الخطوات.")


