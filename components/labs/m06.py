@register("m06_injection_spotter", "اكتشف محاولة حقن الأوامر", "Spot the prompt injection", module=6)
def injection_spotter() -> None:
    st.caption("لكل محتوى وارد: هل يتضمن محاولة **حقن أوامر**؟ انتبه: ليس كل نص مشبوه حقنًا، "
               "وليس كل محتوى سليم أمنيًا صحيحًا معلوماتيًا.")
    with st.form("m06_injection_spotter-form"):
        answers = []
        for i, item in enumerate(INJECTIONS):
            st.markdown(f"**{i + 1}. {item['title']}**")
            st.code(item["text"], language="text")
            answers.append(st.radio("الحكم", ["يحتوي حقنًا", "سليم"], index=None, horizontal=True,
                                    key=f"m06_injection_spotter-{i}", label_visibility="collapsed"))
            st.divider()
        done = st.form_submit_button("صحّح", icon=":material/security:")
    if not done:
        return
    score = 0
    for i, (a, item) in enumerate(zip(answers, INJECTIONS), 1):
        correct = "يحتوي حقنًا" if item["injected"] else "سليم"
        ok = a == correct
        score += ok
        msg = f"**{i}. {item['title']} — {correct}** ({item['kind']})  \n{item['why']}  \n\n**الضابط:** {item['control']}"
        (st.success if ok else st.warning)(msg)
    st.metric("النتيجة", f"{score} / {len(INJECTIONS)}")
    if score >= 5:
        st.success("كشف جيد. تذكّر أن الكشف اليدوي **ليس** حلًا قابلًا للتوسع: الحل في التصميم والصلاحيات.")
    else:
        st.info("راجع أنماط الحقن في المحاضرة 6.4؛ الهدف 5 من 6.")
    st.caption("**الخلاصة الأمنية:** لا تعتمد على قدرتك على اكتشاف الحقن. افترض أنه سيمر أحيانًا، "
               "وصمّم النظام بحيث لا يستطيع أن يفعل شيئًا خطيرًا حتى لو مرّ (المحاضرة 6.5).")
