@register("m08_summary_check", "قائمة الأمانة للتلخيص", "Summary faithfulness check", module=8)
def summary_check() -> None:
    st.caption("التلخيص مهمة **تحويل** لا توليد: كل ما فيه يجب أن يكون في المصدر. "
               "قارن كل ملخص بالنص الأصلي وابحث عن ثلاثة أخطاء: **إضافة**، و**حذف مخلّ**، و**تشويه**.")
    st.markdown("#### النص المصدر")
    st.info(SOURCE)
    choice = st.selectbox("اختر ملخصًا لفحصه", list(SUMMARIES), key="m08_summary_check-choice")
    data = SUMMARIES[choice]
    st.markdown("#### الملخص")
    st.markdown(f"> {data['text']}")
    guess = st.multiselect("ما المشكلات التي تراها؟",
                           ["إضافة معلومة غير موجودة", "حذف معلومة حاسمة", "تشويه يقلب المعنى", "لا مشكلة"],
                           key=f"m08_summary_check-guess-{choice}")
    if not st.button("اكشف التقييم", key=f"m08_summary_check-go-{choice}", icon=":material/visibility:"):
        return
    if data["issues"]:
        st.error(f"**{data['verdict']}**")
        for issue in data["issues"]:
            st.markdown(f"- {issue}")
    else:
        st.success(f"**{data['verdict']}**")
    st.markdown("---")
    st.markdown("**قائمة الأمانة للتلخيص — طبّقها على كل ملخص:**\n"
                "1. هل كل معلومة في الملخص **موجودة** في المصدر؟ (كشف الإضافة)\n"
                "2. هل حُذفت معلومة تغيّر المعنى لبعض القراء؟ (كشف الحذف المخلّ)\n"
                "3. هل تغيّر معنى أي جملة؟ وخصوصًا **النفي** و**الشرط** و**الاستثناء**؟ (كشف التشويه)\n"
                "4. هل نُسب السبب أو الفاعل نسبةً صحيحة؟\n"
                "5. هل تحوّل **احتمال** في المصدر إلى **جزم** في الملخص؟")
