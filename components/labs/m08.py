@register("m08_verification_lab", "مختبر التحقق: اكشف الأخطاء المزروعة", "Verification lab", module=8)
def verification_lab() -> None:
    st.warning("**تنبيه:** النص أدناه **مُعدّ للتدريس** وفيه أخطاء مزروعة عمدًا. وهو يحاكي مخرجًا "
               "نمطيًا من مساعد حواري، وليس مخرجًا حقيقيًا مولَّدًا الآن. الأخطاء من أنواع مختلفة "
               "لتتدرب على تصنيفها.", icon=":material/science:")
    st.markdown("#### النص موضع الفحص")
    st.code(PLANTED_TEXT, language="text")
    st.markdown("#### احكم على كل ادعاء")
    with st.form("m08_verification_lab-form"):
        answers = []
        for c in CLAIMS:
            answers.append(st.radio(f"**{c['id']}.** {c['claim']}",
                                    ["صحيح", "خاطئ", "لست متأكدًا"], index=None, horizontal=True,
                                    key=f"m08_verification_lab-{c['id']}"))
        done = st.form_submit_button("صحّح", icon=":material/fact_check:")
    if not done:
        return
    score = 0
    for a, c in zip(answers, CLAIMS):
        correct = "صحيح" if c["verdict"].startswith("صحيح") else "خاطئ"
        ok = a == correct
        score += ok
        msg = (f"**{c['id']}. الحكم: {c['verdict']}** :gray-badge[{c['kind']}]  \n"
               f"{c['why']}  \n\n**كيف تتحقق؟** {c['how']}")
        (st.success if ok else st.error)(msg)
    st.metric("أحكام صحيحة", f"{score} / {len(CLAIMS)}")
    st.info("**الدرس الأهم:** الفقرة كلها **فصيحة ومتماسكة ومقنعة**. ولم يكن في أسلوبها ما ينبّه إلى "
            "أن أربعة من سبعة ادعاءات خاطئة. **الطلاقة ليست دليل صحة**، والتحقق لا بديل عنه.")
    st.caption("لاحظ أيضًا **تدرج المخاطر**: الادعاء 7 عام ومنخفض الخطورة، والادعاءات 1–4 محددة وعالية "
               "الخطورة لأنها ستُنقل وتُستشهد بها. رتّب تحققك حسب الأثر لا حسب الترتيب في النص.")


