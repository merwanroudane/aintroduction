@register("m08_task_classifier", "صنّف المهمة النصية", "Text task classifier", module=8)
def task_classifier() -> None:
    st.caption("تصنيف المهمة يحدد **مخاطرها** و**طريقة تحققك منها**. وهذه أول خطوة قبل أي استعمال.")
    options = ["استخراج", "تحويل", "توليد", "تصنيف", "استرجاع", "استدلال", "تحقق"]
    with st.form("m08_task_classifier-form"):
        answers = [st.selectbox(f"{i + 1}. {t}", options, index=None, placeholder="اختر الصنف",
                                key=f"m08_task_classifier-{i}")
                   for i, (t, _, _) in enumerate(TASKS)]
        done = st.form_submit_button("صحّح", icon=":material/task_alt:")
    if not done:
        return
    score = sum(a == c for a, (_, c, _) in zip(answers, TASKS))
    st.metric("النتيجة", f"{score} / {len(TASKS)}")
    for i, (a, (t, c, why)) in enumerate(zip(answers, TASKS), 1):
        if a != c:
            st.markdown(f"- **{i}.** الصنف: **{c}** — {why}" + (f" (اخترت: {a})" if a else ""))
    if score >= 6:
        st.success("تصنيف جيد. تذكّر: **الاستخراج والتحويل يُقارنان بالمصدر، والتوليد يُقيَّم بمعايير**.")
    else:
        st.info("راجع جدول الأصناف السبعة في المحاضرة 8.1؛ الهدف 6 من 8.")
