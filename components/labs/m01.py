@register("m01_field_classifier", "إلى أي فرع ينتمي هذا النظام؟", "AI field classifier", module=1)
def field_classifier() -> None:
    st.caption("اختر الفرع الرئيسي لكل نظام. كثير من الأنظمة تستعمل التعلم الآلي منهجًا، لذلك نسأل هنا عن **المهمة** "
               "(لغة، صورة، صوت، فعل مادي…) لا عن المنهج.")
    with st.form("m01_field_classifier-form"):
        answers = []
        for i, (text, _) in enumerate(CASES):
            answers.append(st.selectbox(f"{i + 1}. {text}", FIELDS, index=None, placeholder="اختر الفرع",
                                        key=f"m01_field_classifier-{i}"))
        done = st.form_submit_button("صحّح", icon=":material/task_alt:")
    if not done:
        return
    score = sum(a == c for a, (_, c) in zip(answers, CASES))
    st.metric("النتيجة", f"{score} / {len(CASES)}")
    for i, (a, (text, c)) in enumerate(zip(answers, CASES), 1):
        if a != c:
            st.markdown(f"- **{i}.** الإجابة المتوقعة: **{c}**" + (f" (اخترت: {a})" if a else ""))
    if score >= 10:
        st.success("تمييز جيد بين الفروع. انتقل إلى المحاضرة 1.4.")
    else:
        st.info("راجع جدول الفروع في هذه المحاضرة، ثم أعد المحاولة: الهدف 10 من 12 على الأقل.")


