@register("m01_myth_buster", "صحيح أم خطأ؟ اختبر تصوراتك", "Myth buster", module=1)
def myth_buster() -> None:
    st.caption("صوّت على كل عبارة قبل قراءة المحاضرة، ثم أعد التصويت بعدها. التصحيح يظهر بعد الضغط على «اكشف».")
    with st.form("m01_myth_buster-form"):
        votes = [st.segmented_control(f"{i + 1}. {text}", ["صحيح", "خطأ", "لا أعرف"], key=f"m01_myth_buster-{i}")
                 for i, (text, _, _) in enumerate(MYTHS)]
        reveal = st.form_submit_button("اكشف", icon=":material/visibility:")
    if not reveal:
        return
    right = 0
    for i, (vote, (text, answer, why)) in enumerate(zip(votes, MYTHS), 1):
        ok = vote == answer
        right += ok
        (st.success if ok else st.info)(f"**{i}. {answer}.** {why}")
    st.metric("تصورات صحيحة", f"{right} / {len(MYTHS)}")
