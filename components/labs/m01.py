@register("m01_function_sorter", "صنّف النظام حسب وظيفته", "Function sorter", module=1)
def function_sorter() -> None:
    st.caption("لكل نظام، اختر الوظيفة أو الوظائف التي يؤديها ثم اضغط «تحقق». قد تكون هناك أكثر من إجابة صحيحة.")
    with st.form("m01_function_sorter-form"):
        picks = []
        for i, (text, _, _) in enumerate(SYSTEMS):
            st.markdown(f"**{i + 1}.** {text}")
            picks.append(st.pills("الوظائف", FUNCTIONS, selection_mode="multi", key=f"m01_function_sorter-{i}",
                                  label_visibility="collapsed"))
        done = st.form_submit_button("تحقق", icon=":material/fact_check:")
    if not done:
        return
    score = 0
    for i, (text, answer, why) in enumerate(SYSTEMS):
        chosen = set(picks[i] or [])
        ok = chosen == answer
        score += ok
        missing, extra = answer - chosen, chosen - answer
        msg = f"**{i + 1}.** " + ("صحيح. " if ok else "") + why
        if not ok:
            if missing:
                msg += f"  \nينقصك: {'، '.join(sorted(missing))}."
            if extra:
                msg += f"  \nزائد: {'، '.join(sorted(extra))}."
        (st.success if ok else st.warning)(msg)
    st.metric("إجابات مطابقة تمامًا", f"{score} / {len(SYSTEMS)}")


