@register("m05_diagnose_prompt", "شخّص المكوّن الناقص", "Diagnose the missing component", module=5)
def diagnose_prompt() -> None:
    st.caption("لكل شكوى، حدد المكوّن الناقص في الأمر. هذه أهم مهارة عملية في المحور: "
               "**تحويل الإحباط من المخرج إلى تشخيص قابل للإصلاح**.")
    options = [c[1] for c in COMPONENT_FIELDS]
    with st.form("m05_diagnose_prompt-form"):
        answers = [st.selectbox(f"{i + 1}. {t}", options, index=None, placeholder="المكوّن الناقص",
                                key=f"m05_diagnose_prompt-{i}")
                   for i, (t, _, _) in enumerate(DIAGNOSE)]
        done = st.form_submit_button("صحّح", icon=":material/task_alt:")
    if not done:
        return
    score = sum(a == c for a, (_, c, _) in zip(answers, DIAGNOSE))
    st.metric("النتيجة", f"{score} / {len(DIAGNOSE)}")
    for i, (a, (t, c, fix)) in enumerate(zip(answers, DIAGNOSE), 1):
        ok = a == c
        (st.success if ok else st.warning)(f"**{i}.** المكوّن: **{c}** — {fix}" +
                                           ("" if ok else f"  \n(اخترت: {a})" if a else ""))
    if score >= 6:
        st.success("تشخيص جيد. انتقل إلى دورة التحسين المنضبطة في المحاضرة 5.4.")
    else:
        st.info("راجع جدول المكونات التسعة في المحاضرة 5.1، ثم أعد المحاولة: الهدف 6 من 8.")
