@register("m05_prompt_lab", "مختبر الأوامر: ابنِ أمرًا وقيّم بنيته", "Prompt laboratory", module=5)
def prompt_lab() -> None:
    st.caption("املأ ما تحتاجه من المكونات، ثم اضغط «ركّب وقيّم». التقييم **بنيوي**: يفحص اكتمال الأمر "
               "وليس تقييمًا من نموذج لجودة المخرج. الهدف أن ترى أثر كل مكوّن على وضوح الأمر.")
    with st.form("m05_prompt_lab-form"):
        values = {}
        c1, c2 = st.columns(2)
        for i, (key, label, placeholder, help_text) in enumerate(COMPONENT_FIELDS):
            col = c1 if i % 2 == 0 else c2
            values[key] = col.text_area(label, placeholder=placeholder, help=help_text,
                                        height=80, key=f"m05_prompt_lab-{key}")
        done = st.form_submit_button("ركّب وقيّم", icon=":material/build:")
    if not done:
        return

    order = ["role", "task", "context", "audience", "constraints", "examples", "format", "success", "input"]
    labels = {k: lab for k, lab, _, _ in COMPONENT_FIELDS}
    parts = []
    for key in order:
        v = (values.get(key) or "").strip()
        if not v:
            continue
        if key == "input":
            parts.append(f"### {labels[key]}\n<<<\n{v}\n>>>")
        else:
            parts.append(f"### {labels[key]}\n{v}")
    assembled = "\n\n".join(parts)

    if not assembled:
        st.warning("لم تملأ أي مكوّن بعد.")
        return

    st.markdown("#### الأمر المركّب")
    st.code(assembled, language="markdown")
    st.download_button("تنزيل الأمر", assembled, file_name="prompt.md", mime="text/markdown",
                       icon=":material/download:", key="m05_prompt_lab-dl")

    present = {k for k in values if (values.get(k) or "").strip()}
    weights = {"task": 25, "format": 15, "success": 15, "constraints": 12, "context": 10,
               "audience": 8, "input": 8, "examples": 4, "role": 3}
    score = sum(w for k, w in weights.items() if k in present)

    st.markdown("#### قائمة التحقق البنيوية")
    for key, label, _, help_text in COMPONENT_FIELDS:
        ok = key in present
        icon = ":material/check_circle:" if ok else ":material/cancel:"
        color = "green" if ok else "red"
        st.markdown(f":{color}[{icon}] **{label}** ({weights[key]} نقطة) — :gray[{help_text}]")
    st.metric("اكتمال بنيوي", f"{score} / 100")

    missing = [labels[k] for k in weights if k not in present]
    if missing:
        st.info("**المكونات الناقصة وأثرها المتوقع:**\n" + "\n".join(
            f"- **{labels[k]}**: " + {
                "task": "لن يعرف النموذج ما المطلوب أصلًا؛ هذا أخطر نقص.",
                "format": "سيختار النموذج شكلًا عشوائيًا (فقرة بدل جدول مثلًا).",
                "success": "لن تستطيع أنت ولا النموذج الحكم على جودة الناتج.",
                "constraints": "قد يضيف معلومات من خارج المدخل أو يتجاوز الطول المناسب.",
                "context": "قد يكون الناتج صحيحًا لكنه غير مناسب للغرض.",
                "audience": "قد يكون المستوى اللغوي والمصطلحي غير مناسب للقارئ.",
                "input": "إن كانت المهمة على نص محدد، فبدون فصله قد يختلط بالتعليمات.",
                "examples": "قد يختلف الشكل بين تشغيل وآخر؛ الأمثلة تثبّته.",
                "role": "أثره محدود، وهو الأقل أهمية بين المكونات.",
            }[k] for k in weights if k not in present))
    if score >= 85:
        st.success("أمر مكتمل البنية. الخطوة التالية: اختبره على **مجموعة حالات ثابتة** لا على حالة واحدة (المحاضرة 5.4).")
    elif score >= 60:
        st.warning("بنية مقبولة وينقصها ما ذُكر أعلاه. أضف المكوّن الأعلى وزنًا من الناقص أولًا.")
    else:
        st.error("بنية ضعيفة: راجع المكونات التسعة في المحاضرة 5.1.")
    st.caption("**تنبيه:** هذا التقييم بنيوي فقط. اكتمال البنية لا يضمن صحة المخرج، "
               "والتحقق من المحتوى موضوع المحور 8.")


