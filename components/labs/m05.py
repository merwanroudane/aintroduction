@register("m05_prompt_ladder_lab", "من أمر ضعيف إلى أمر منظم", "Weak → improved → structured", module=5)
def prompt_ladder_lab() -> None:
    st.caption("اختر مهمة، ثم انتقل بين المستويات الثلاثة، واقرأ تحليل سبب التحسن في كل خطوة.")
    task = st.selectbox("المهمة", list(LADDER), key="m05_prompt_ladder_lab-task")
    data = LADDER[task]
    level = st.segmented_control("المستوى", ["ضعيف", "محسَّن", "منظم"], default="ضعيف",
                                 key="m05_prompt_ladder_lab-level", required=True)
    key = {"ضعيف": "weak", "محسَّن": "improved", "منظم": "structured"}[level]
    st.code(data[key], language="markdown")
    counts = {"ضعيف": 1, "محسَّن": 2, "منظم": 3}[level]
    st.progress(counts / 3, text=f"مستوى البنية: {counts} من 3")
    if level != "ضعيف":
        idx = 0 if level == "محسَّن" else 1
        title, body = data["analysis"][idx]
        st.markdown(f"**{title}:** {body}")
    if level == "منظم":
        title, body = data["analysis"][2]
        st.success(f"**{title}:** {body}", icon=":material/lightbulb:")


